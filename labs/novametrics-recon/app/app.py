from flask import Flask, render_template, Response, make_response

app = Flask(__name__)

FLAG3 = "FLAG{h3ad3rs_t3ll_0n_th3ms3lv3s}"
FLAG4 = "FLAG{g1t_c0nf1g_l3ft_1n_pr0d}"
FLAG6 = "FLAG{backup_f1l3s_n3v3r_r3ally_h1dd3n}"


@app.route("/")
def home():
    resp = make_response(render_template("home.html"))
    # VULNERABLE (intentionally, for recon practice): a leftover internal
    # build header, the kind of thing that leaks in response headers from
    # a CI/CD pipeline that was never scrubbed for production.
    resp.headers["X-Build-Info"] = f"novametrics-web build#4471 deployer=ci-runner-03 note={FLAG3}"
    return resp


