@app.route("/.git/config")
def git_config():
    # Simulates a deployment that pushed the .git directory to the web
    # root by accident -- a genuinely common real-world finding.
    content = f"""[core]
\trepositoryformatversion = 0
\tfilemode = true
\tbare = false
\tlogallrefupdates = true
[remote "origin"]
\turl = git@internal-gitlab.novametrics.local:web/novametrics-site.git
\tfetch = +refs/heads/*:refs/remotes/origin/*
# deploy note: {FLAG4}
[branch "main"]
\tremote = origin
\tmerge = refs/heads/main
"""
    return Response(content, mimetype="text/plain")


@app.route("/backup.sql")
def backup_sql():
    # Simulates a forgotten database backup left in the web root --
    # exactly the kind of file a content-discovery wordlist (ffuf/
    # gobuster against SecLists) is built to find.
    content = f"""-- novametrics production dump (auto, DO NOT COMMIT)
-- generated by backup-cron on db-primary
-- {FLAG6}
CREATE TABLE staff_notes (id INT, note TEXT);
INSERT INTO staff_notes VALUES (1, 'rotate the staging creds before Q3');
"""
    return Response(content, mimetype="text/plain")


